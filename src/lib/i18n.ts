/**
 * useTranslation - returns a function `t(key)` that resolves to the current
 * language's string, or falls back to the English string, or the raw key.
 *
 * Usage:
 *   const t = useTranslation();
 *   <h1>{t("dashboard")}</h1>
 */
export function useTranslation(): (key: string, fallbackOrOptions?: string | Record<string, any>) => string {
  // Import useValtrioxStore dynamically to avoid circular dependency
  // eslint-disable-next-line @typescript-eslint/no-require-imports
  const { useValtrioxStore } = require("@/store/brandflow-store");
  const lang = useValtrioxStore((s: any) => s.language) || "en";
  return (key: string, fallbackOrOptions?: string | Record<string, any>) => {
    const template =
      translations[lang]?.[key] ||
      translations.en[key] ||
      (typeof fallbackOrOptions === "string" ? fallbackOrOptions : key);
    if (typeof fallbackOrOptions === "object" && fallbackOrOptions !== null) {
      return template.replace(/\{(\w+)\}/g, (_, token) => fallbackOrOptions[token] ?? "");
    }
    return template;
  };
}

/**
 * t() - standalone function (not a hook) that takes a language explicitly.
 */
export function t(lang: Language, key: string, fallbackOrOptions?: string | Record<string, any>): string {
  const template = translations[lang]?.[key] || translations.en[key] || (typeof fallbackOrOptions === "string" ? fallbackOrOptions : key);
  if (typeof fallbackOrOptions === "object" && fallbackOrOptions !== null) {
    return template.replace(/\{(\w+)\}/g, (_, token) => fallbackOrOptions[token] ?? "");
  }
  return template;
}

